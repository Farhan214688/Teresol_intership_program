#include <iostream>
using namespace std;
int main()
{
    int a;
    cout<<"Enter a integer to convert it into float: "<<endl;
    cin>>a;
    cout<<"A is "<<(float)a<<endl;

    float b;
    cout<<"Enter a float to convert it into int: "<<endl;
    cin>>b;
    cout<<"A is "<<(int)b<<endl;
    
}